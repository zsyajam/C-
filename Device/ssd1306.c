static HAL_StatusTypeDef WriteCommand(uint8_t command)
{
    uint8_t packet[2] = {0x00U, command};
    return HAL_I2C_Master_Transmit(&hi2c1, SSD1306_ADDR, packet, 2U, 100U);
}

HAL_StatusTypeDef SSD1306_Init(void)
{
    static const uint8_t commands[] = {
        0xAE,0x20,0x00,0xB0,0xC8,0x00,0x10,0x40,0x81,0x7F,0xA1,0xA6,
        0xA8,0x3F,0xA4,0xD3,0x00,0xD5,0x80,0xD9,0xF1,0xDA,0x12,0xDB,
        0x40,0x8D,0x14,0xAF
    };
    uint32_t i;
    HAL_Delay(100U);
    for (i = 0U; i < sizeof(commands); ++i) {
        if (WriteCommand(commands[i]) != HAL_OK) return HAL_ERROR;
    }
    SSD1306_Clear();
    return SSD1306_Update();
}

void SSD1306_Clear(void)
{
    memset(s_buffer, 0, sizeof(s_buffer));
}

static void DrawChar(uint8_t x, uint8_t page, char c)
{
    uint8_t column;
    if ((c >= 'a') && (c <= 'z')) c = (char)(c - 'a' + 'A');
    if ((c < ' ') || (c > 'Z') || (x > 122U) || (page > 7U)) c = '?';
    for (column = 0U; column < 5U; ++column)
        s_buffer[(uint16_t)page * SSD1306_WIDTH + x + column] = s_font[(uint8_t)c - 32U][column];
    s_buffer[(uint16_t)page * SSD1306_WIDTH + x + 5U] = 0U;
}

void SSD1306_DrawString(uint8_t x, uint8_t y, const char *text)
{
    uint8_t page = (uint8_t)(y / 8U);
    while ((*text != '\0') && (x <= 122U)) {
        DrawChar(x, page, *text++);
        x = (uint8_t)(x + 6U);
    }
}

HAL_StatusTypeDef SSD1306_Update(void)
{
    uint8_t page;
    uint8_t packet[129];
    packet[0] = 0x40U;
    for (page = 0U; page < 8U; ++page) {
        if (WriteCommand((uint8_t)(0xB0U + page)) != HAL_OK) return HAL_ERROR;
        if (WriteCommand(0x00U) != HAL_OK) return HAL_ERROR;
        if (WriteCommand(0x10U) != HAL_OK) return HAL_ERROR;
        memcpy(&packet[1], &s_buffer[(uint16_t)page * SSD1306_WIDTH], SSD1306_WIDTH);
        if (HAL_I2C_Master_Transmit(&hi2c1, SSD1306_ADDR, packet, sizeof(packet), 100U) != HAL_OK) return HAL_ERROR;
    }
    return HAL_OK;
}
